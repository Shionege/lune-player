/* ==========================================================================
   Seekbar Drag Controls
   ========================================================================== */
function initSeekbarDragControls() {
  const track = document.getElementById('seekbar-track');
  const fill = document.getElementById('seekbar-fill');
  const thumb = document.getElementById('seekbar-thumb');
  const timeElapsed = document.getElementById('time-elapsed');

  let dragPercent = 0;

  const updateSeekPosFromEvent = (e) => {
    const rect = track.getBoundingClientRect();
    const clientX = e.touches ? e.touches[0].clientX : e.clientX;
    const clickX = clientX - rect.left;
    dragPercent = Math.max(0, Math.min(1, clickX / rect.width));

    fill.style.width = `${dragPercent * 100}%`;
    thumb.style.left = `${dragPercent * 100}%`;

    if (playerEngine.audio.duration) {
      const seekSec = dragPercent * playerEngine.audio.duration;
      timeElapsed.textContent = formatTime(seekSec);
    }
  };

  const startDrag = (e) => {
    isDraggingSeekbar = true;
    thumb.classList.add('dragging');
    updateSeekPosFromEvent(e);
  };

  const moveDrag = (e) => {
    if (!isDraggingSeekbar) return;
    updateSeekPosFromEvent(e);
  };

  const stopDrag = () => {
    if (!isDraggingSeekbar) return;
    isDraggingSeekbar = false;
    thumb.classList.remove('dragging');
    if (playerEngine.audio.duration) {
      playerEngine.seek(dragPercent * playerEngine.audio.duration);
    }
  };

  track.addEventListener('mousedown', startDrag);
  window.addEventListener('mousemove', moveDrag);
  window.addEventListener('mouseup', stopDrag);

  track.addEventListener('touchstart', startDrag, { passive: true });
  window.addEventListener('touchmove', moveDrag, { passive: true });
  window.addEventListener('touchend', stopDrag);
}

