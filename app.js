async function loadLibrarySongs() {
  try {
    allSongs = await musicStorage.getAllSongs();
    applyFilterAndSearch();
  } catch (e) {
    console.error("Failed to load songs from IndexedDB:", e);
  }
}

function applyFilterAndSearch() {
  filteredSongs = allSongs.filter((song) => {
    const matchesSearch = searchQuery === '' || 
      song.title.toLowerCase().includes(searchQuery) ||
      song.artist.toLowerCase().includes(searchQuery) ||
      song.album.toLowerCase().includes(searchQuery);

    if (!matchesSearch) return false;

    if (currentFilter === 'favorites') return song.isFavorite;
    return true;
  });

  renderLibrarySongs();
}

function renderLibrarySongs() {
  const listContainer = document.getElementById('library-song-list');
  const emptyView = document.getElementById('library-empty');
  const countLabel = document.getElementById('library-count');

  countLabel.textContent = `${filteredSongs.length} Songs`;

  if (filteredSongs.length === 0) {
    listContainer.innerHTML = '';
    emptyView.style.display = 'block';
    return;
  }

  emptyView.style.display = 'none';
  const currentSong = playerEngine.getCurrentSong();

  listContainer.innerHTML = filteredSongs.map((song, index) => {
    const isPlaying = currentSong && currentSong.id === song.id;
    const cleanTitle = (song.title || '').replace(/\[e\]/gi, '').trim();
    const coverSrc = safeCreateObjectURL(song.coverBlob, getDefaultCoverUrl(cleanTitle, song.artist));
    const isChecked = selectedMultiSongIds.has(song.id);

    return `
      <div class="song-card ${isPlaying ? 'playing' : ''} ${isMultiSelectMode ? 'multi-selecting' : ''}" data-id="${song.id}" data-index="${index}">
        ${isMultiSelectMode ? `<input type="checkbox" class="song-card-checkbox" ${isChecked ? 'checked' : ''} data-song-id="${song.id}">` : ''}
        <div class="song-art-wrapper">
          <img src="${coverSrc}" class="song-art" alt="" onerror="this.src='${getDefaultCoverUrl()}'">
          <div class="soundwave-overlay">
            <div class="wave-bar"></div>
            <div class="wave-bar"></div>
            <div class="wave-bar"></div>
          </div>
        </div>
        <div class="song-info">
          <div class="song-title-row">
            <span class="song-title">${escapeHtml(cleanTitle)}</span>
            ${song.explicit ? '<span class="explicit-badge">E</span>' : ''}
          </div>
          <div class="song-subtext">${escapeHtml(song.artist)}</div>
        </div>
        <div class="song-actions">
          <span style="font-size: 12px; color: var(--text-muted); font-family: monospace; margin-right: 4px;">${formatTime(song.duration)}</span>
          ${!isMultiSelectMode ? `
            <button class="action-btn favorite ${song.isFavorite ? 'active' : ''}" data-action="favorite" data-id="${song.id}">
              ${song.isFavorite ? '♥' : '♡'}
            </button>
            <button class="action-btn" data-action="delete" data-id="${song.id}">🗑️</button>
          ` : ''}
        </div>
      </div>
    `;
  }).join('');

  const songCards = listContainer.querySelectorAll('.song-card');

  songCards.forEach((card) => {
    const songId = card.dataset.id;
    const index = parseInt(card.dataset.index, 10);

    /* Touch & Mouse Long-Press Handlers (500ms) */
    const startPress = () => {
      longPressTimer = setTimeout(() => {
        if (!isMultiSelectMode) {
          isMultiSelectMode = true;
          selectedMultiSongIds.clear();
          selectedMultiSongIds.add(songId);
          updateMultiSelectUI();
          renderLibrarySongs();
        }
      }, 500);
    };

    const cancelPress = () => {
      if (longPressTimer) {
        clearTimeout(longPressTimer);
        longPressTimer = null;
      }
    };

    card.addEventListener('mousedown', startPress);
    card.addEventListener('mouseup', cancelPress);
    card.addEventListener('mouseleave', cancelPress);
    card.addEventListener('touchstart', startPress, { passive: true });
    card.addEventListener('touchend', cancelPress);
    card.addEventListener('touchmove', cancelPress);

    card.addEventListener('click', (e) => {
      if (e.target.closest('.action-btn')) return;

      if (isMultiSelectMode) {
        if (selectedMultiSongIds.has(songId)) {
          selectedMultiSongIds.delete(songId);
        } else {
          selectedMultiSongIds.add(songId);
        }
        updateMultiSelectUI();
        renderLibrarySongs();
      } else {
        hasUserPlayedAudio = true;
        currentSourcePlaylistName = null;
        playerEngine.setQueue(filteredSongs, index);
        playerEngine.play();
        showMiniPlayer();
      }
    });
  });

  /* Favorite clicks are now handled by Global Event Delegation */

  listContainer.querySelectorAll('[data-action="delete"]').forEach((btn) => {
    btn.addEventListener('click', async (e) => {
      e.stopPropagation();
      const songId = btn.dataset.id;
      if (confirm("Delete this song from offline storage?")) {
        await musicStorage.deleteSong(songId);
        await loadLibrarySongs();
        await renderPlaylists();
      }
    });
  });
}

