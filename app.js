function safeCreateObjectURL(blob, fallbackUrl = '') {
  if (!blob) return fallbackUrl;
  if (typeof blob === 'string') return blob;
  try {
    if (blob instanceof Blob || blob instanceof File) {
      return URL.createObjectURL(blob);
    }
  } catch (e) {
    console.warn("safeCreateObjectURL error:", e);
  }
  return fallbackUrl;
}

function initDefaultPlayerUI() {
  const current = playerEngine.getCurrentSong() || allSongs[0];
  if (current) {
    const cleanTitle = (current.title || '').replace(/\[e\]/gi, '').trim();
    const defaultArt = safeCreateObjectURL(current.coverBlob, getDefaultCoverUrl(cleanTitle, current.artist));
    
    // Get actual queue/list for previous/next images
    const queue = playerEngine.queue.length > 0 ? playerEngine.queue : allSongs;
    const currentIndex = playerEngine.queue.length > 0 ? playerEngine.currentIndex : 0;
    
    const prevSong = queue[currentIndex - 1] || queue[queue.length - 1];
    const prevClean = prevSong ? (prevSong.title || '').replace(/\[e\]/gi, '').trim() : '';
    const prevArt = safeCreateObjectURL(prevSong?.coverBlob, getDefaultCoverUrl(prevClean, ''));
    
    const nextSong = queue[currentIndex + 1] || queue[0];
    const nextClean = nextSong ? (nextSong.title || '').replace(/\[e\]/gi, '').trim() : '';
    const nextArt = safeCreateObjectURL(nextSong?.coverBlob, getDefaultCoverUrl(nextClean, ''));

    const miniArt = document.getElementById('mini-art-img');
    const imgCenter = document.getElementById('carousel-card-center') || document.getElementById('carousel-center');
    const imgLeft = document.getElementById('carousel-card-left') || document.getElementById('carousel-left');
    const imgRight = document.getElementById('carousel-card-right') || document.getElementById('carousel-right');

    if (miniArt) miniArt.src = defaultArt;
    if (imgCenter) imgCenter.src = defaultArt;
    if (imgLeft) imgLeft.src = prevArt;
    if (imgRight) imgRight.src = nextArt;

    const miniTitle = document.getElementById('mini-song-title');
    const miniArtist = document.getElementById('mini-song-artist');
    const sheetTitle = document.getElementById('sheet-song-title');
    const sheetArtist = document.getElementById('sheet-song-artist');
    const miniBadge = document.getElementById('mini-explicit-badge');
    const sheetBadge = document.getElementById('sheet-explicit-badge');

    if (miniTitle) miniTitle.textContent = cleanTitle;
    if (miniArtist) miniArtist.textContent = current.artist;
    if (sheetTitle) sheetTitle.textContent = cleanTitle;
    if (sheetArtist) sheetArtist.textContent = current.artist;
    if (miniBadge) miniBadge.style.display = current.explicit ? 'inline-block' : 'none';
    if (sheetBadge) sheetBadge.style.display = current.explicit ? 'inline-block' : 'none';
  }
  /* Keep mini player hidden until user taps play */
  hasUserPlayedAudio = false;
  const mini = document.getElementById('floating-mini-player');
  if (mini) {
    mini.style.display = 'none';
    mini.classList.remove('visible');
  }
}

